#Addition
num1 = int(input("Enter the 1st value for addition : "))
num2 = int(input("Enter the 2nd value for addition : "))
add = num1 + num2
print(f"The addition of {num1} and {num2} is {add}")

#Division
num3 = int(input("Enter the 1st value for division : "))
num4 = int(input("Enter the 2nd value for division : "))
division = num3 / num4
if num4 == 0:
    print("0 can't divided")
else:
    print(f"The division of {num3} and {num4} is{division}")